"""Adversarial integration tests for proxy / Host header hardening.

These tests pin the *behavioural* contract of the request pipeline configured
by ``app.main``. They bypass ``uvicorn``'s ``--proxy-headers`` flag entirely
and inject the ASGI scope directly so we can assert, with deterministic peer
IPs, Host headers and forwarded headers, that:

- A request whose immediate peer is **not** in ``TRUSTED_FORWARDED_PROXIES``
  cannot smuggle a different scheme/host/client IP via ``X-Forwarded-*`` or
  the RFC 7239 ``Forwarded`` header.
- A request whose immediate peer **is** trusted promotes exactly the
  forwarded headers to ``scope["scheme"]``, ``scope["server"]`` and
  ``scope["client"]`` — once and only once.
- The ``TrustedHost`` enforcer rejects unknown hosts with ``400`` and accepts
  the configured public hosts as well as the cloudflared-emitted ``Host``
  (``127.0.0.1:8000``) when explicitly listed.
- Redirects generated by ``StaticFiles(html=True)`` for ``/app`` and by the
  router for ``/api/v1/health/`` (trailing slash) preserve the public origin
  when the peer is trusted, and never leak an internal loopback origin to a
  hostile peer.
- HSTS is emitted only when the *external* scheme is HTTPS, never in
  development, and never carries ``includeSubDomains`` unless explicitly
  configured.
- ``/docs``, ``/redoc`` and ``/openapi.json`` are gated to ``development`` and
  never serve a schema outside that environment.

These tests are RED-first: the production ASGI middleware and the
configuration wiring do not yet exist, so they fail with
``ImportError``/``AttributeError``/``400``/``307`` until
``app.core.proxy`` exposes ``ProxyHeadersMiddleware`` /
``TrustedHostEnforcerMiddleware`` and ``app.main`` wires them. The assertions
below describe the *intended* contract and must all pass once the
implementation matches the spec.
"""
from __future__ import annotations

from collections.abc import AsyncIterator
from typing import Any

import pytest

# ── Helpers ─────────────────────────────────────────────────────────────────


def _build_scope(
    *,
    path: str,
    peer: tuple[str, int],
    host_header: str,
    headers: list[tuple[bytes, bytes]] | None = None,
    scheme: str = "http",
) -> dict[str, Any]:
    """Build a minimal ASGI HTTP scope for direct invocation.

    Returns a scope dict compatible with Starlette's HTTPConnection. The
    ``headers`` list is augmented with a synthetic ``host`` header taken from
    ``host_header`` if not already present.
    """
    if headers is None:
        headers = []
    has_host = any(k.lower() == b"host" for k, _ in headers)
    if not has_host:
        headers = [*headers, (b"host", host_header.encode("latin-1"))]
    return {
        "type": "http",
        "asgi": {"version": "3.0", "spec_version": "2.3"},
        "http_version": "1.1",
        "method": "GET",
        "scheme": scheme,
        "path": path,
        "raw_path": path.encode("latin-1"),
        "query_string": b"",
        "headers": headers,
        "server": (host_header.partition(":")[0], int(host_header.rpartition(":")[2]) if ":" in host_header else 80),
        "client": peer,
        "root_path": "",
        "extensions": {},
    }


async def _invoke(scope: dict[str, Any]) -> tuple[int, list[tuple[bytes, bytes]], bytes]:
    """Invoke the ASGI app with ``scope`` and return ``(status, headers, body)``."""
    from app.main import app  # imported lazily so tests can monkeypatch settings first

    sent: list[dict[str, Any]] = []

    async def receive() -> dict[str, Any]:
        return {"type": "http.request", "body": b"", "more_body": False}

    async def send(message: dict[str, Any]) -> None:
        sent.append(message)

    # Strip query string that ASGITransport would otherwise attach.
    await app(scope, receive, send)

    start = next(m for m in sent if m["type"] == "http.response.start")
    body = b"".join(m.get("body", b"") for m in sent if m["type"] == "http.response.body")
    return start["status"], start.get("headers", []), body


