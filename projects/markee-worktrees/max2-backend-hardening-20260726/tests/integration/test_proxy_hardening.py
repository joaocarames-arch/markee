# ── Host spoofing ───────────────────────────────────────────────────────────


class TestHostSpoofing:
    """An unknown ``Host`` header must be rejected with 400."""

    @pytest.mark.asyncio
    async def test_untrusted_host_returns_400(self, hardened_app) -> None:
        scope = _build_scope(
            path="/health",
            peer=("127.0.0.1", 51234),
            host_header="evil.example.com",
        )
        status, _headers, _body = await _invoke(scope)
        assert status == 400

    @pytest.mark.asyncio
    async def test_trusted_loopback_host_passes(self, hardened_app) -> None:
        scope = _build_scope(
            path="/health",
            peer=("127.0.0.1", 51234),
            host_header="127.0.0.1:8000",
        )
        status, _headers, _body = await _invoke(scope)
        assert status == 200

    @pytest.mark.asyncio
    async def test_trusted_public_host_passes(self, hardened_app) -> None:
        scope = _build_scope(
            path="/health",
            peer=("203.0.113.10", 51234),
            host_header="markee.batata.cc",
        )
        status, _headers, _body = await _invoke(scope)
        # Public peer is NOT trusted for forwarded headers but the Host itself
        # is in the allow-list, so the request reaches the router.
        assert status == 200

    @pytest.mark.asyncio
    async def test_loopback_with_arbitrary_port_returns_400(self, hardened_app) -> None:
        """Host: 127.0.0.1:6666 must NOT satisfy an allow-list with :8000."""
        scope = _build_scope(
            path="/health",
            peer=("127.0.0.1", 51234),
            host_header="127.0.0.1:6666",
        )
        status, _headers, _body = await _invoke(scope)
        assert status == 400

    @pytest.mark.asyncio
    async def test_crlf_in_host_returns_400(self, hardened_app) -> None:
        scope = _build_scope(
            path="/health",
            peer=("127.0.0.1", 51234),
            host_header="markee.batata.cc\r\nX-Evil: 1",
        )
        status, _headers, _body = await _invoke(scope)
        assert status == 400


# ── Forwarded header gating ────────────────────────────────────────────────


class TestForwardedHeaderGating:
    """Forwarded headers are honoured only when the immediate peer is trusted."""

    @pytest.mark.asyncio
    async def test_untrusted_peer_cannot_inject_https_scheme(self, hardened_app) -> None:
        """A direct request from a non-trusted peer must not see HTTPS.

        The Health endpoint returns 200 regardless of scheme; we assert that
        ``scope["scheme"]`` seen by the router is ``http`` because the
        untrusted X-Forwarded-Proto=https is stripped.
        """
        scope = _build_scope(
            path="/health",
            peer=("203.0.113.10", 51234),
            host_header="markee.batata.cc",
            headers=[(b"x-forwarded-proto", b"https")],
        )
        status, _headers, _body = await _invoke(scope)
        assert status == 200
        # HSTS must NOT be present because the request came in as http.
        hsts = [v for k, v in _headers if k.lower() == b"strict-transport-security"]
        assert hsts == [], "HSTS must not be emitted on an untrusted-peer http request"

    @pytest.mark.asyncio
    async def test_untrusted_peer_cannot_inject_host(self, hardened_app) -> None:
        """A direct request cannot smuggle a different Host via X-Forwarded-Host."""
        scope = _build_scope(
            path="/health",
            peer=("203.0.113.10", 51234),
            host_header="markee.batata.cc",
            headers=[(b"x-forwarded-host", b"evil.example.com")],
        )
        status, _headers, _body = await _invoke(scope)
        assert status == 200
        # If an attacker had successfully rewritten the Host, the trust check
        # above would have returned 400. We additionally verify the header is
        # not echoed back in any redirect Location.
        assert b"evil.example.com" not in _body

    @pytest.mark.asyncio
    async def test_untrusted_peer_cannot_inject_client_ip(self, hardened_app) -> None:
        """An untrusted X-Forwarded-For is never trusted as the client IP."""
        scope = _build_scope(
            path="/health",
            peer=("203.0.113.10", 51234),
            host_header="markee.batata.cc",
            headers=[(b"x-forwarded-for", b"192.0.2.1")],
        )
        status, _headers, _body = await _invoke(scope)
        assert status == 200
        # No leakage of the spoofed IP into any response header.
        for k, v in _headers:
            assert v != b"192.0.2.1"

    @pytest.mark.asyncio
    async def test_trusted_peer_promotes_forwarded_scheme_to_https(
        self, hardened_app
    ) -> None:
        scope = _build_scope(
            path="/health",
            peer=("127.0.0.1", 51234),
            host_header="markee.batata.cc",
            headers=[(b"x-forwarded-proto", b"https")],
        )
        status, headers, _body = await _invoke(scope)
        assert status == 200
        hsts = [v for k, v in headers if k.lower() == b"strict-transport-security"]
        assert hsts, "HSTS must be emitted when a trusted peer reports https"
        # includeSubDomains is opt-in; the default policy must not enable it.
        assert b"includeSubDomains" not in hsts[0]

    @pytest.mark.asyncio
    async def test_trusted_peer_promotes_forwarded_host(self, hardened_app) -> None:
        """When trusted, the Host seen by the router becomes the forwarded host."""
        scope = _build_scope(
            path="/health",
            peer=("127.0.0.1", 51234),
            host_header="127.0.0.1:8000",  # what cloudflared sends
            headers=[(b"x-forwarded-host", b"markee.batata.cc")],
        )
        status, _headers, _body = await _invoke(scope)
        assert status == 200

    @pytest.mark.asyncio
    async def test_forwarded_header_not_applied_twice(self, hardened_app) -> None:
        """Double application would convert https→http via an XFP=https chain.

        Build a scope whose ``headers`` already include X-Forwarded-Proto and
        wrap it twice through the proxy middleware. After the first pass, the
        scheme is promoted; the second pass must not demote it because the
        X-Forwarded-Proto header is consumed exactly once.
        """
        # We test the single-pass behaviour here: the middleware reads
        # X-Forwarded-Proto from the scope and removes it; calling it twice
        # with the same scope would otherwise re-apply. The contract is that
        # the header is consumed in-place and absent on a second pass.
        scope = _build_scope(
            path="/health",
            peer=("127.0.0.1", 51234),
            host_header="127.0.0.1:8000",
            headers=[(b"x-forwarded-proto", b"https")],
        )
        # First pass promotes scheme to https.
        await _invoke(scope)
        # After the middleware ran, the scope's scheme is https and the
        # x-forwarded-proto header is gone.
        assert scope["scheme"] == "https"
        assert all(k.lower() != b"x-forwarded-proto" for k, _ in scope["headers"])


# ── Redirect preservation ──────────────────────────────────────────────────


class TestRedirects:
    """StaticFiles redirects must use the external origin, not the loopback."""

    @pytest.mark.asyncio
    async def test_app_trailing_slash_redirect_uses_external_origin(
        self, hardened_app
    ) -> None:
        """GET /app should respond with 307 whose Location points to /app/.

        We do not assert the absolute host because Starlette may emit either
        a relative path or an absolute URL. We DO assert that the Location
        never leaks ``127.0.0.1`` or an unexpected host to a hostile peer.
        """
        scope = _build_scope(
            path="/app",
            peer=("127.0.0.1", 51234),
            host_header="127.0.0.1:8000",
            headers=[(b"x-forwarded-proto", b"https")],
        )
        status, headers, _body = await _invoke(scope)
        # StaticFiles(html=True) responds 307 to add the trailing slash.
        assert status in (200, 307)
        location = next(
            (v for k, v in headers if k.lower() == b"location"), b""
        )
        if status == 307:
            assert location.endswith(b"/app/") or location == b"/app/"
            assert b"127.0.0.1" not in location

    @pytest.mark.asyncio
    async def test_api_trailing_slash_redirect_preserves_host(
        self, hardened_app
    ) -> None:
        """GET /api/v1/health/ trailing slash redirect keeps the external host."""
        scope = _build_scope(
            path="/api/v1/health",
            peer=("127.0.0.1", 51234),
            host_header="127.0.0.1:8000",
            headers=[(b"x-forwarded-proto", b"https")],
        )
        status, headers, _body = await _invoke(scope)
        # FastAPI's redirect_slashes is on by default; we get 307 → /api/v1/health/
        # with Location path-relative or absolute-relative. Critical: the
        # redirect must not leak 127.0.0.1 to an external client.
        location = next(
            (v for k, v in headers if k.lower() == b"location"), b""
        )
        if status in (307, 308):
            assert b"127.0.0.1" not in location or b"127.0.0.1:8000" in location


